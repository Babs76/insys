using System.Text.Json;
using Insys.BuildingBlocks.Application.Context;
using Insys.BuildingBlocks.Application.Messaging;
using Insys.BuildingBlocks.Contracts;
using Insys.General.Contracts;
using Insys.ProductFactory.Contracts;

namespace Insys.Documents.Application;

/// <summary>
/// Documents' reactions to General's policies (domain-model.json: document consumes GeneralPolicyIssued → schedule and
/// certificate; GeneralPolicyEndorsed → the endorsement type's documents). The templates are those assigned to the product
/// (product.cfg_product_template_assignments). A failure is retried and then dead-lettered, and regenerated by
/// replaying it; the policy is never rolled back (process "General quote to cash").
/// </summary>
public sealed class GeneralDocumentPolicies(DocumentGenerator generator, ISellableProducts products, DocumentLanguages languages, ITenantContext tenant, IBusinessDate businessDate) :
    IIntegrationEventHandler<GeneralPolicyIssued>,
    IIntegrationEventHandler<GeneralPolicyEndorsed>,
    IIntegrationEventHandler<GeneralRenewalInvited>
{
    /// <summary>A renewal invitation (GEN-004) from the renewal rule's invitation template, in the policyholder's language (addendum §5).</summary>
    public async Task Handle(GeneralRenewalInvited invited, EventEnvelope envelope, CancellationToken cancellationToken)
    {
        var template = await languages.Template(invited.TemplateCode, await languages.Chain(invited.PolicyholderPartyId, cancellationToken), cancellationToken)
                       ?? throw new PrerequisiteMissingException(PrerequisiteCodes.DocumentTemplateNotInForce, invited.TemplateCode);
        var data = JsonSerializer.SerializeToElement(new Dictionary<string, object?>
        {
            ["policy_number"] = invited.PolicyNumber, ["product_code"] = invited.ProductCode, ["period_end"] = invited.PeriodEnd.ToString("yyyy-MM-dd"),
        }, JsonSerializerOptions.Web);
        var document = await generator.Generate(new GenerateDocument(template.TemplateCode, template.Language, template.DocumentType, GeneralDocuments.PolicyRefType,
            invited.PolicyId, $"{invited.ProductCode} v{invited.ProductVersion}", null, data), cancellationToken);
        if (document.IsFailure)
        {
            throw new InvalidOperationException($"The renewal invitation for {invited.PolicyNumber} was not generated: {document.Error.Message}");
        }
    }

    /// <summary>The document types generated at issue. TODO(spec): the issuance document set is named in the process, not configured (OQ-059).</summary>
    public static readonly string[] IssueDocuments = ["POLICY_SCHEDULE", "CERTIFICATE"];

    public Task Handle(GeneralPolicyIssued issued, EventEnvelope envelope, CancellationToken cancellationToken) =>
        Generate(issued.ProductCode, issued.ProductVersion, IssueDocuments, issued.PolicyholderPartyId, GeneralDocuments.PolicyRefType, issued.PolicyId, new Dictionary<string, object?>
        {
            ["policy_number"] = issued.PolicyNumber, ["product_code"] = issued.ProductCode, ["product_version"] = issued.ProductVersion,
            ["period_start"] = issued.PeriodStart.ToString("yyyy-MM-dd"), ["period_end"] = issued.PeriodEnd.ToString("yyyy-MM-dd"),
            ["annual_premium"] = issued.AnnualPremium, ["currency"] = issued.Currency,
        }, cancellationToken);

    public Task Handle(GeneralPolicyEndorsed endorsed, EventEnvelope envelope, CancellationToken cancellationToken) =>
        Generate(endorsed.ProductCode, endorsed.ProductVersion, [.. endorsed.DocumentTypes], endorsed.PolicyholderPartyId, GeneralDocuments.EndorsementRefType, endorsed.EndorsementId,
            new Dictionary<string, object?>
            {
                ["policy_number"] = endorsed.PolicyNumber, ["endorsement_number"] = endorsed.EndorsementNumber, ["effective_date"] = endorsed.EffectiveDate.ToString("yyyy-MM-dd"),
                ["annual_premium"] = endorsed.NewAnnualPremium, ["premium_delta"] = endorsed.PremiumDelta, ["currency"] = endorsed.Currency,
            }, cancellationToken);

    private async Task Generate(string productCode, int productVersion, string[] documentTypes, Guid? recipientPartyId, string businessRefType, Guid businessRefId,
        Dictionary<string, object?> fields, CancellationToken cancellationToken)
    {
        // One template per document type, in the recipient's language by the chain (addendum §5).
        var assigned = await products.Templates(tenant.RequireTenantId(), productCode, businessDate.Today, cancellationToken);
        var chain = await languages.Chain(recipientPartyId, cancellationToken);
        var templates = documentTypes.Select(type => DocumentLanguages.Pick(assigned, type, chain)).OfType<ProductTemplate>().ToList();
        var missing = documentTypes.Where(type => templates.All(t => t.DocumentType != type)).ToList();
        if (missing.Count > 0)
        {
            throw new PrerequisiteMissingException(PrerequisiteCodes.DocumentTemplateNotInForce, $"{productCode}:{string.Join(",", missing)}");
        }

        var data = JsonSerializer.SerializeToElement(fields, JsonSerializerOptions.Web);
        foreach (var template in templates)
        {
            var document = await generator.Generate(new GenerateDocument(template.TemplateCode, template.Language, template.DocumentType, businessRefType, businessRefId,
                $"{productCode} v{productVersion}", null, data), cancellationToken);
            if (document.IsFailure)
            {
                throw new InvalidOperationException($"{template.DocumentType} for {businessRefType} {businessRefId} was not generated: {document.Error.Message}");
            }
        }
    }
}

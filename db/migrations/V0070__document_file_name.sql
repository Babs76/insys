-- V0070: an uploaded document keeps the name its file was uploaded with (BR-027), so the front end can offer it again on
-- download. Generated documents, and uploads made before V0070, have none.
-- =====================================================================
ALTER TABLE document.document ADD COLUMN file_name varchar(255);

COMMENT ON COLUMN document.document.file_name IS
  'The uploaded file''s name, without any path (BR-027); NULL for generated documents and for uploads made before V0070. Not written to logs or events.';
